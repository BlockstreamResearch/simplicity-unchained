//! Runs base jets on an environment that wraps their own.
//!
//! `JetEnvironment::c_jet_ptr` must return a plain `fn` pointer, so a base jet can't be wrapped in
//! a closure that swaps the outer env for the base C env. Instead, every base jet gets its own
//! trampoline, a `fn` monomorphized over the jet's index in `ALL`.
use simplicity::ffi::CFrameItem;
use simplicity::jet::{Core, CoreEnv, Elements, ElementsTxEnv, Jet, JetEnvironment};

use super::bitcoin::CoreExtension;
use super::elements::ElementsExtension;
use super::environments::{BitcoinUnchainedEnv, ElementsUnchainedEnv, UnchainedEnv};

/// C jet function running on an environment of type `W`.
pub type JetFn<W> = fn(&mut CFrameItem, CFrameItem, &W) -> bool;

/// Upper bound on the number of jets in a base jet set, see [`fn_table`].
const MAX_BASE_JETS: usize = 512;

/// A base jet set together with the environment its C implementations run on.
pub trait BaseJet: Jet + Copy {
    type Env: JetEnvironment<Jet = Self>;

    /// All jets of the set, indexed by [`BaseJet::index`].
    const ALL: &'static [Self];

    /// Position of `self` inside [`BaseJet::ALL`].
    fn index(&self) -> usize;
}

/// An environment that holds the environment of a base jet set.
pub trait AsBaseEnv<E> {
    fn base_env(&self) -> &E;
}

impl<E> AsBaseEnv<E> for UnchainedEnv<E> {
    fn base_env(&self) -> &E {
        &self.env
    }
}

impl BaseJet for Core {
    type Env = CoreEnv;
    const ALL: &'static [Self] = &Core::ALL;

    fn index(&self) -> usize {
        *self as usize
    }
}

impl BaseJet for Elements {
    type Env = ElementsTxEnv;
    const ALL: &'static [Self] = &Elements::ALL;

    fn index(&self) -> usize {
        *self as usize
    }
}

impl BaseJet for CoreExtension {
    type Env = BitcoinUnchainedEnv;
    const ALL: &'static [Self] = &CoreExtension::ALL;

    fn index(&self) -> usize {
        match self {
            CoreExtension::Core(inner) => inner.index(),
            CoreExtension::GetOpcodeFromScript => Core::ALL.len(),
            CoreExtension::GetPubkeyFromScript => Core::ALL.len() + 1,
        }
    }
}

impl BaseJet for ElementsExtension {
    type Env = ElementsUnchainedEnv;
    const ALL: &'static [Self] = &ElementsExtension::ALL;

    fn index(&self) -> usize {
        match self {
            ElementsExtension::Elements(inner) => inner.index(),
            ElementsExtension::GetOpcodeFromScript => Elements::ALL.len(),
            ElementsExtension::GetPubkeyFromScript => Elements::ALL.len() + 1,
        }
    }
}

/// Returns the C implementation of a base jet, adapted to run on `W`.
pub fn base_c_jet_ptr<J: BaseJet, W: AsBaseEnv<J::Env>>(jet: &J) -> JetFn<W> {
    const { assert!(J::ALL.len() <= MAX_BASE_JETS) };

    Trampolines::<J, W>::TABLE.as_flattened().as_flattened()[jet.index()]
}

fn trampoline<J: BaseJet, W: AsBaseEnv<J::Env>, const I: usize>(
    dst: &mut CFrameItem,
    src: CFrameItem,
    env: &W,
) -> bool {
    let c_jet = <J::Env as JetEnvironment>::c_jet_ptr(&J::ALL[I]);
    c_jet(dst, src, env.base_env().c_jet_env())
}

/// Builds a `[[[_; 8]; 8]; 8]` table of `$f::<J, W, I>` for every `I` below [`MAX_BASE_JETS`].
// TODO: refactor into something less ugly, e.g. a flat table generated by a proc macro.
macro_rules! fn_table {
    ($f:ident) => {
        fn_table!(@a $f; 0 1 2 3 4 5 6 7)
    };
    (@a $f:ident; $($a:literal)*) => {
        [$(fn_table!(@b $f; $a; 0 1 2 3 4 5 6 7)),*]
    };
    (@b $f:ident; $a:literal; $($b:literal)*) => {
        [$(fn_table!(@c $f; $a; $b; 0 1 2 3 4 5 6 7)),*]
    };
    (@c $f:ident; $a:literal; $b:literal; $($c:literal)*) => {
        [$($f::<J, W, { $a * 64 + $b * 8 + $c }> as JetFn<W>),*]
    };
}

struct Trampolines<J, W>(J, W);

impl<J: BaseJet, W: AsBaseEnv<J::Env>> Trampolines<J, W> {
    #[allow(clippy::type_complexity)]
    const TABLE: [[[JetFn<W>; 8]; 8]; 8] = fn_table!(trampoline);
}

#[cfg(test)]
mod tests {
    use super::*;

    fn assert_indices<J: BaseJet>() {
        for (i, jet) in J::ALL.iter().enumerate() {
            assert_eq!(jet.index(), i, "{jet}");
        }
    }

    #[test]
    fn index_matches_position_in_all() {
        assert_indices::<Core>();
        assert_indices::<Elements>();
        assert_indices::<CoreExtension>();
        assert_indices::<ElementsExtension>();
    }
}
