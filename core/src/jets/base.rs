//! Runs base jets (`Core`, `Elements`) on an [`UnchainedEnv`].
//!
//! `JetEnvironment::c_jet_ptr` must return a plain `fn` pointer, so a base jet can't be wrapped in
//! a closure that swaps the unchained env for the base C env. Instead, every base jet gets its own
//! trampoline, a `fn` monomorphized over the jet's index in `ALL`.
use simplicity::ffi::CFrameItem;
use simplicity::jet::{Core, CoreEnv, Elements, ElementsTxEnv, Jet, JetEnvironment};

use super::environments::UnchainedEnv;

/// C jet function running on an [`UnchainedEnv`].
pub type UnchainedJetFn<E> = fn(&mut CFrameItem, CFrameItem, &UnchainedEnv<E>) -> bool;

/// Upper bound on the number of jets in a base jet set, see [`fn_table`].
const MAX_BASE_JETS: usize = 512;

/// A base jet set together with the environment its C implementations run on.
pub trait BaseJet: Jet + Copy {
    type Env: JetEnvironment<Jet = Self>;

    /// All jets of the set, indexed by [`BaseJet::index`].
    const ALL: &'static [Self];

    /// Position of `self` inside [`BaseJet::ALL`].
    fn index(&self) -> usize;
}

impl BaseJet for Core {
    type Env = CoreEnv;
    const ALL: &'static [Self] = &Core::ALL;

    fn index(&self) -> usize {
        *self as usize
    }
}

impl BaseJet for Elements {
    type Env = ElementsTxEnv;
    const ALL: &'static [Self] = &Elements::ALL;

    fn index(&self) -> usize {
        *self as usize
    }
}

/// Returns the C implementation of a base jet, adapted to run on an [`UnchainedEnv`].
pub fn base_c_jet_ptr<J: BaseJet>(jet: &J) -> UnchainedJetFn<J::Env> {
    const { assert!(J::ALL.len() <= MAX_BASE_JETS) };

    Trampolines::<J>::TABLE.as_flattened().as_flattened()[jet.index()]
}

fn trampoline<J: BaseJet, const I: usize>(
    dst: &mut CFrameItem,
    src: CFrameItem,
    env: &UnchainedEnv<J::Env>,
) -> bool {
    let c_jet = <J::Env as JetEnvironment>::c_jet_ptr(&J::ALL[I]);
    c_jet(dst, src, env.env.c_jet_env())
}

/// Builds a `[[[_; 8]; 8]; 8]` table of `$f::<J, I>` for every `I` below [`MAX_BASE_JETS`].
// TODO: refactor into something less ugly, e.g. a flat table generated by a proc macro.
macro_rules! fn_table {
    ($f:ident) => {
        fn_table!(@a $f; 0 1 2 3 4 5 6 7)
    };
    (@a $f:ident; $($a:literal)*) => {
        [$(fn_table!(@b $f; $a; 0 1 2 3 4 5 6 7)),*]
    };
    (@b $f:ident; $a:literal; $($b:literal)*) => {
        [$(fn_table!(@c $f; $a; $b; 0 1 2 3 4 5 6 7)),*]
    };
    (@c $f:ident; $a:literal; $b:literal; $($c:literal)*) => {
        [$($f::<J, { $a * 64 + $b * 8 + $c }> as UnchainedJetFn<J::Env>),*]
    };
}

struct Trampolines<J>(J);

impl<J: BaseJet> Trampolines<J> {
    #[allow(clippy::type_complexity)]
    const TABLE: [[[UnchainedJetFn<J::Env>; 8]; 8]; 8] = fn_table!(trampoline);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn index_matches_position_in_all() {
        for (i, jet) in Core::ALL.iter().enumerate() {
            assert_eq!(jet.index(), i, "{jet}");
        }
        for (i, jet) in Elements::ALL.iter().enumerate() {
            assert_eq!(jet.index(), i, "{jet}");
        }
    }
}
